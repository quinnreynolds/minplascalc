r"""Hand-sized analytic evaluation of eq. 18 -- the shippable version.

This is the code generated by ``q_analytic_symbolic``, written out.  The
sympy module is the derivation and the proof; this is what would go into
``functions_transport.py``, and it needs no symbolic dependency at runtime.

Derivation summary (full version in ``ANALYTIC_RECURSION.md``):

.. math::

    \ln \Omega^{\star} = g(x) = c\,\sigma_1 + a_4 \sigma_2,
    \quad c = a_0 + a_1 x,
    \quad \sigma_1 = \sigma(k_1(x - a_2)),
    \quad \sigma_2 = \sigma(k_2(x - a_5))

with :math:`k_1 = 2/a_3`, :math:`k_2 = 2/a_6`,
:math:`d_i = \sigma_i(1-\sigma_i)`, and

.. math::

    g'  &= a_1 \sigma_1 + c k_1 d_1 + a_4 k_2 d_2 \\
    g'' &= 2 a_1 k_1 d_1 + c k_1^2 d_1 (1 - 2\sigma_1)
           + a_4 k_2^2 d_2 (1 - 2\sigma_2)

Eq. 18 with :math:`T\partial_T = \partial_x` and
:math:`\Omega^{\star}_{(k)} = e^{g}P_k` gives
:math:`P_{k+1} = P_k + (g' P_k + P_k')/(s_0+k+2)`, i.e.

.. math::

    P_0 = 1, \quad
    P_1 = 1 + \frac{g'}{s_0+2}, \quad
    P_2 = P_1 + \frac{g' P_1 + g''/(s_0+2)}{s_0+3}
"""

import numpy as np

# Largest tabulated moment order per l; above this the recursion applies.
BASE_S = {1: 5, 2: 4, 3: 3, 4: 4}


def omega_star(x, a, k, s0):
    r"""Reduced collision integral at moment order ``s0 + k``.

    Analytic evaluation of eq. 18 of [Laricchiuta2007]_ -- no finite
    differences.

    Parameters
    ----------
    x : float
        :math:`\ln T^{\star}`.
    a : np.ndarray
        Length-7 fit coefficients of eq. 16.
    k : int
        Recursion steps above the tabulated order (0, 1 or 2 in practice).
    s0 : int
        Largest tabulated moment order for this ``l``.

    Returns
    -------
    float
        :math:`\\Omega^{\\star}`.
    """
    a0, a1, a2, a3, a4, a5, a6 = a
    k1, k2 = 2 / a3, 2 / a6
    c = a0 + a1 * x

    s1 = 1 / (1 + np.exp(-k1 * (x - a2)))
    s2 = 1 / (1 + np.exp(-k2 * (x - a5)))

    g = c * s1 + a4 * s2
    if k == 0:
        return np.exp(g)

    d1, d2 = s1 * (1 - s1), s2 * (1 - s2)
    g1 = a1 * s1 + c * k1 * d1 + a4 * k2 * d2
    P = 1 + g1 / (s0 + 2)
    if k == 1:
        return np.exp(g) * P

    g2 = (
        2 * a1 * k1 * d1
        + c * k1**2 * d1 * (1 - 2 * s1)
        + a4 * k2**2 * d2 * (1 - 2 * s2)
    )
    P = P + (g1 * P + g2 / (s0 + 2)) / (s0 + 3)
    return np.exp(g) * P
